def render_hits(hits: Sequence[Hit]) -> str:
    """Нумерованный список цитат с подсветкой совпадения.

    Номер нужен, чтобы вердикт мог сослаться на конкретную находку: без ссылки
    цитату из ответа невозможно сверить с тем, что действительно передавали.
    """
    lines = []
    for number, hit in enumerate(hits, start=1):
        where = hit.file_name or "карточка закупки"
        if hit.page:
            where = f"{where}, стр. {hit.page}"
        lines.append(f"[{number}] {where}\n{hit.highlighted()}")
    return "\n\n".join(lines)


def render_card(
    name: str | None, description: str | None, customer: str | None, okpd2: str | None
) -> str:
    parts = [
        f"Наименование: {name or '—'}",
        f"Заказчик: {customer or '—'}",
        f"ОКПД2: {okpd2 or '—'}",
    ]
    if description:
        parts.append(f"Описание: {description}")
    return "\n".join(parts)

"""Решение модели по спорной закупке.

Модель зовут не для того, чтобы она прочитала документацию, а для того, чтобы
она разобрала несколько цитат. Разница принципиальная: в прогоне ХПК/БПК
классификация 76 закупок по цитатам заняла один проход и оказалась однозначной,
тогда как отобранные по смыслу фрагменты документации отвечают на вопрос
«о чём документ», а не «что значит вот это упоминание».
"""

from __future__ import annotations

from pydantic import BaseModel, Field

#: Версия промпта судьи. Входит в ключ кэша вместе с версией критериев: правка
#: формулировки обязана обесценить прежние решения, а не смешаться с ними.
JUDGE_PROMPT_VERSION = "hits-judge-v1"


class EvidenceItem(BaseModel):
    """Цитата, на которой держится вывод.

    `hit_number` — номер находки из тех, что были переданы модели. Ссылка на
    конкретную находку, а не свободный текст: только так вывод можно проверить.
    """

    hit_number: int
    quote: str = ""


class ModelVerdict(BaseModel):
    """То, что модель отвечает по одной закупке."""

    match: bool
    score: float = Field(ge=0.0, le=1.0, default=0.0)
    reasoning: str = ""
    evidence: list[EvidenceItem] = Field(default_factory=list)

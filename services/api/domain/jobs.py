"""Состояние длительной операции — то, по чему рисуется шкала ожидания.

Отдельный модуль, а не поле в словаре: экран обязан отличать «не знаю сколько»
от «нисколько». Пока задание отдавалось нетипизированным `dict`, эти два
состояния были неразличимы, и клиент дорисовывал ноль процентов там, где
знаменателя ещё никто не считал.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime


@dataclass(slots=True)
class JobView:
    job_id: str
    kind: str
    status: str
    #: Какая фаза идёт сейчас. `processed`/`total` считаются **внутри** неё:
    #: у обхода корпуса и у судьи цена единицы работы разная, и сквозной
    #: процент по обеим был бы выдуманным числом.
    phase: str | None
    #: Объём текущей фазы. `None` — объём ещё не известен (сборка сводки узнаёт
    #: его только после кластеризации). Это не то же самое, что ноль.
    total: int | None
    processed: int
    result: dict[str, object] | None
    error: str | None
    #: Когда задание началось. Без него нельзя показать ни «идёт столько-то»,
    #: ни оценку остатка — а без них шкала не отличается от волчка.
    created_at: datetime
    updated_at: datetime

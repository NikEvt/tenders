"""Когда суточную выгрузку можно считать окончательной.

ЕИС отдаёт извещения суточными архивами, и архив за незакончившийся день
дописывается до полуночи. Значит, успешная выгрузка сама по себе ещё ничего не
говорит о полноте: выгрузив сегодняшний архив в полдень, мы получим половину
дня — и, если пометить день закрытым, вторую половину не заберём уже никогда.

Это не гипотетическая осторожность. Дозаказ периода пропускает сочетания
«регион × тип × день», помеченные успехом, — свойство, ради которого заявку
можно слать сколько угодно раз. Без правила ниже оно превращалось бы в
постоянную дыру в покрытии: один заказ, задевший сегодня, закрывал бы день
навсегда.

Отсюда же берётся ручное обновление: сегодняшний день просто никогда не
считается закрытым, поэтому кнопка работает без флага «перекачать всё равно».
Второй способ сказать то же самое не нужен.

Само правило живёт в `libs/shared/day_completeness.py`: тот же вопрос задаёт
сборка сводки, а двух ответов у него быть не должно.
"""

from __future__ import annotations

from datetime import date

from libs.shared.day_completeness import is_closed


def is_final(target_date: date, ran_at: date) -> bool:
    """Закрыт ли день выгрузкой, состоявшейся `ran_at`."""
    return is_closed(target_date, ran_at)

"""Что считать смысловым совпадением.

Векторный поиск возвращает ближайших независимо от того, насколько они близки.
Пока эмбеддингов меньше, чем размер пула, «ближайшие» — это весь корпус: до
введения порога запрос «мебель» отдавал 302 закупки из 302 существующих, хотя
слово встречалось в трёх.

Порог измерен, а не выбран: `scripts/calibrate_similarity.py` считает близость
по десяти запросам, из которых два заведомо чужие корпусу и задают уровень шума.

    запрос                          лучшее   медиана
    поставка кислорода в баллонах    0.672     0.367
    ремонт кровли                    0.645     0.285
    медицинские перчатки             0.586     0.391
    услуги охраны                    0.535     0.305
    ── чужие корпусу ────────────────────────────────
    запуск спутника на орбиту        0.427     0.288
    дрессировка служебных собак      0.407     0.268

Потолок шума 0.427, худшее верное попадание 0.535 — между ними просвет, и 0.48
делит его пополам. Просвет узкий: при смене модели эмбеддингов калибровку нужно
повторить, иначе порог начнёт срезать верные совпадения.

Одного абсолютного числа мало. Длинный описательный запрос лежит ближе ко всему
подряд, чем короткий: у семантического запроса фильтра «ХПК» (28 слов) медиана
близости по всему корпусу — 0.478, то есть ровно на уровне порога, и сквозь него
проходит половина базы. Поднять число нельзя: короткие запросы начнут терять
верные совпадения уже на 0.55.

Поэтому отсечки две, и работают они вместе:

* абсолютная отвечает на «похоже ли это хоть на что-то»;
* относительная — на «похоже ли это настолько же, насколько лучшее совпадение
  этого запроса». Она подстраивается под запрос сама: у «ХПК» лучшее
  совпадение 0.697, и хвост на 0.48 к нему отношения не имеет.
"""

from __future__ import annotations

import os

#: Ниже этого косинусная близость считается шумом.
DEFAULT_SEMANTIC_FLOOR = 0.48

#: Доля от лучшего совпадения запроса, ниже которой результат отбрасывается.
#: 0.9 — то есть «отстаёт от лидера не более чем на десятую часть».
DEFAULT_RELATIVE_FLOOR = 0.9


def semantic_floor(variable: str = "SEMANTIC_SIMILARITY_FLOOR") -> float:
    """Порог близости с возможностью переопределить переменной окружения.

    Имя переменной — параметр: у поиска в каталоге и у отбора кандидатов для
    судьи разные цены ошибки. Каталогу дороже показать мусор, судье — упустить
    подходящую закупку, и со временем пороги могут разойтись осознанно.
    """
    raw = os.getenv(variable, "")
    try:
        value = float(raw)
    except ValueError:
        return DEFAULT_SEMANTIC_FLOOR
    # Косинусная близость нормированных векторов лежит в [-1, 1]; за границами
    # порог обессмысливается, поэтому явная опечатка в конфиге игнорируется.
    return value if -1.0 <= value <= 1.0 else DEFAULT_SEMANTIC_FLOOR


def relative_floor(variable: str = "SEMANTIC_RELATIVE_FLOOR") -> float:
    """Доля от лучшего совпадения запроса, ниже которой результат — хвост.

    Считается по уже отобранным кандидатам, а не в SQL: лучшее совпадение
    известно только после запроса, и отдельный проход ради него удвоил бы
    стоимость поиска.
    """
    raw = os.getenv(variable, "")
    try:
        value = float(raw)
    except ValueError:
        return DEFAULT_RELATIVE_FLOOR
    # Ноль отключил бы отсечку, единица оставила бы только лидера.
    return value if 0.0 < value <= 1.0 else DEFAULT_RELATIVE_FLOOR


def cut_tail(scored: list[tuple[int, float]], relative: float) -> list[int]:
    """Оставляет то, что сопоставимо с лучшим совпадением запроса.

    `scored` отсортирован по убыванию близости.
    """
    if not scored:
        return []
    best = scored[0][1]
    if best <= 0:
        return [key for key, _ in scored]
    return [key for key, score in scored if score >= best * relative]

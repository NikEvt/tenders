"""Когда календарный день можно считать закрытым.

Правило маленькое, но его спрашивают из разных мест и по разным поводам:

- краулер — чтобы не пометить суточный архив ЕИС выгруженным, пока он
  дописывается до полуночи;
- сборка сводки — чтобы не заморозить навсегда сводку, собранную в середине
  дня, который ещё шёл.

Оба вопроса — один и тот же: **успело ли наблюдение застать конец дня.** Пока
ответов было два, второй просто отсутствовал: сводка за 13 августа осталась
навсегда с четырьмястами закупками из четырёх с половиной тысяч, потому что
собрали её раньше, чем доехали данные, а пересобрать было некому.

Живёт в `libs.shared`, потому что это свойство календаря, а не какого-то
сервиса, и потому что сервисы не импортируют друг друга.
"""

from __future__ import annotations

from datetime import date


def is_closed(day: date, observed_at: date) -> bool:
    """Закрыт ли `day` наблюдением, состоявшимся `observed_at`.

    Закрыт, только если наблюдение шло уже после его окончания — то есть на
    следующие сутки или позже. Наблюдение того же дня остаётся частичным, каким
    бы полным ни выглядел его результат.
    """
    return observed_at > day

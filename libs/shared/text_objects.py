"""Извлечённый текст как объект в хранилище, а не как поле в таблице.

Полный текст документа — самое крупное, что производит обработка вложений, и
самое редко читаемое. В Postgres он лежал в `document_texts.content` и тянул за
собой TOAST: операционная база росла на десятки гигабайт ради данных, которые
читают двое — просмотрщик документа и выравниватель смещений чанков.
Полнотекстовый поиск по `content` не идёт вовсе, он работает по `document_chunks`.

Поэтому текст уезжает в объектное хранилище, а в таблице остаётся ключ.

**Что остаётся в Postgres — `document_chunks.text`.** Перенести его нельзя:
`search_tsv` объявлен генерируемым столбцом `to_tsvector('russian', text)`, на
нём GIN-индекс и весь лексический поиск по документации. Плюс на чанках висят
эмбеддинги и по ним же цитирует судья. Правило простое: крупное и редко
читаемое — в хранилище, мелкое и индексируемое — в базе.

**Ключ — от содержимого, а не от документа.** Типовой проект контракта или
памятка участнику приложены к тысячам извещений, и текст у них побайтово
одинаков. Ключ по sha256 текста делает дедупликацию свойством схемы имён:
одинаковый текст физически хранится один раз, сколько бы документов на него ни
ссылалось.
"""

from __future__ import annotations

import hashlib

#: Префикс пространства имён в бакете.
TEXT_PREFIX = "texts"

#: Кодировка объекта. Явная: текст приходит из OCR и битых CMap, и полагаться
#: на локаль хранилища здесь нельзя.
TEXT_ENCODING = "utf-8"

TEXT_CONTENT_TYPE = "text/plain; charset=utf-8"


def text_digest(content: str) -> str:
    """sha256 текста — он же основа ключа и признак дубликата."""
    return hashlib.sha256(content.encode(TEXT_ENCODING)).hexdigest()


def text_key(digest: str) -> str:
    """Ключ объекта по его хешу.

    Первые два символа выносятся в отдельный уровень: у S3-совместимых хранилищ
    листинг и шардирование опираются на префикс, и сотни тысяч объектов в одном
    «каталоге» превращают любой обзор бакета в долгую операцию.
    """
    return f"{TEXT_PREFIX}/{digest[:2]}/{digest}.txt"


def encode_text(content: str) -> bytes:
    return content.encode(TEXT_ENCODING)


def decode_text(raw: bytes) -> str:
    # Текст мог прийти из OCR с обрывками суррогатов; терять из-за них весь
    # документ незачем — непредставимое заменяется, остальное читается.
    return raw.decode(TEXT_ENCODING, errors="replace")

def normalize_region_code(raw: str | None) -> str | None:
    """Приводит код к двузначному виду.

    ЕИС шлёт то `77`, то `077`, то `7`. Всё, что не похоже на номер субъекта,
    возвращается как есть: столбец свободный, и молча портить неизвестное
    значение хуже, чем оставить его нераспознанным.
    """
    if raw is None:
        return None
    code = raw.strip()
    if not code.isdigit():
        return code or None
    return code.lstrip("0").zfill(2)


def is_known_region(code: str | None) -> bool:
    """Есть ли такой субъект в справочнике.

    Проверка пользовательского ввода: опечатка в коде даёт прогон, который
    ничего не прочитал и отчитался чистой воронкой нулей — ложноотрицательный
    результат в обличье настоящего.
    """
    return normalize_region_code(code) in RUSSIAN_REGIONS


def region_name(code: str | None) -> str:
    """Название субъекта или сам код, если он незнаком.

    Запасной вариант несущий, а не оборонительный: столбец свободный, и код за
    пределами справочника — обычное дело, а не сбой.
    """
    if not code or code == UNKNOWN_REGION:
        return UNKNOWN_REGION
    normalized = normalize_region_code(code)
    if normalized is None:
        return UNKNOWN_REGION
    return RUSSIAN_REGIONS.get(normalized, f"Регион {code}")
